import { CONSENT_CUSTOMER, CONSENT_PARTNER } from "@/lib/join/privacy-docs";
import { ISSUER, type LegalSection } from "@/lib/join/legal";

/** หนังสือให้ความยินยอม (Consent Form) เป็นหน้าเว็บ — ให้ความยินยอมด้วยการติ๊กในแอป (บันทึกเวอร์ชัน + เวลา) แทนการลงชื่อบนกระดาษ */
export function consentSections(kind: "partner" | "customer"): LegalSection[] {
  const c = kind === "partner" ? CONSENT_PARTNER : CONSENT_CUSTOMER;
  return [
    { h: "ผู้ให้ความยินยอม", p: [`ข้าพเจ้า เจ้าของข้อมูลส่วนบุคคล ให้ความยินยอมแก่ ${ISSUER.name} (ต่อไปนี้เรียกว่า “บริษัทฯ”) ในการเก็บรวบรวม ใช้หรือเปิดเผยข้อมูลส่วนบุคคลของข้าพเจ้า เพื่อวัตถุประสงค์ ดังนี้`] },
    { h: "วัตถุประสงค์", li: c.purposes },
    { h: "การให้และถอนความยินยอม", p: c.tail },
    {
      h: "วิธีให้ความยินยอม",
      p: kind === "partner"
        ? ["ผู้สมัครให้ความยินยอมโดยติ๊กในหน้าชำระค่าสมัคร ระบบบันทึกเวอร์ชันของหนังสือนี้และวันเวลาที่ให้ความยินยอม · ความยินยอมตรวจสอบประวัติอาชญากรรมและข้อมูลผลตรวจสุขภาพ (ข้อ ๖ ข้อมูลอ่อนไหว) แยกติ๊กต่างหาก", `ขอถอนความยินยอมได้ทุกเมื่อ ทางอีเมล ${ISSUER.email} หรือโทร ${ISSUER.phone}`]
        : ["ลูกค้าให้ความยินยอมโดยติ๊กในหน้าสมัครสมาชิก ระบบบันทึกเวอร์ชันของหนังสือนี้และวันเวลาที่ให้ความยินยอม", `ขอถอนความยินยอมได้ทุกเมื่อ ทางอีเมล ${ISSUER.email} หรือโทร ${ISSUER.phone}`],
    },
  ];
}
